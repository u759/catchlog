"""Builds species_aliases rows mapping BC fish species codes (e.g. 'RB') to our species ids.

Inputs (argv): <bc_fish_species_codes.csv> <fishbase_synonyms.parquet> <species_seed.sql> <out.sql>
  - BC code table: export from the BC Fish Information Data Query (FIDQ) "Fish Species" search
    (a100.gov.bc.ca/pub/fidq/viewFishSpecies.do -> exportFishSpecies.do). Columns: SPECIES_CODE, COMMON_NAME,
    SCIENTIFIC_NAME. Code -> scientific-name pairs are facts; we only store the mapping.
  - FishBase synonyms (v26.06 parquet) to resolve outdated scientific names.
Requires duckdb.
"""
import csv
import re
import sys

import duckdb

codes_csv, synonyms_parquet, seed_sql, out_path = sys.argv[1:5]

seed = open(seed_sql, encoding='utf-8').read()
species = {}  # scientific -> id
for m in re.finditer(r"^\s+\('([^']+)', '(?:[^']|'')*', (?:'(?:[^']|'')*'|null), '((?:[^']|'')*)'", seed, re.M):
    species[m.group(2).replace("''", "'")] = m.group(1)
by_common = {}
for m in re.finditer(r"^\s+\('([^']+)', '((?:[^']|'')*)'", seed, re.M):
    by_common[m.group(2).replace("''", "'").lower()] = m.group(1)

con = duckdb.connect()
syn = {}
for genus, sp, valid_code in con.execute(
    f"select SynGenus, SynSpecies, SpecCode from '{synonyms_parquet}' where SynGenus is not null and SynSpecies is not null"
).fetchall():
    syn.setdefault(f'{genus} {sp}', set()).add(valid_code)
valid = {f'{g} {s}': c for g, s, c in con.execute(
    f"select Genus, Species, SpecCode from '{synonyms_parquet.replace('synonyms', 'species')}'").fetchall()}
code_to_sci = {}
for name, code in valid.items():
    code_to_sci.setdefault(code, name)


def resolve(sci: str):
    sci = ' '.join(sci.split())
    if not sci:
        return None
    binomial = ' '.join(sci.split()[:2])
    for cand in (sci, binomial, binomial + 'i', re.sub(r'i$', 'ii', binomial)):
        if cand in species:
            return species[cand]
    codes = syn.get(binomial) or syn.get(binomial + 'i')
    if codes and len(codes) == 1:
        current = code_to_sci.get(next(iter(codes)))
        if current in species:
            return species[current]
    return None


rows, unmatched = [], []
for r in csv.DictReader(open(codes_csv, encoding='utf-8', errors='replace')):
    code = (r.get('SPECIES_CODE') or '').strip()
    if not code:
        continue
    sid = resolve(r.get('SCIENTIFIC_NAME') or '') or by_common.get((r.get('COMMON_NAME') or '').strip().lower())
    if sid:
        rows.append((code, sid))
    else:
        unmatched.append((code, r.get('COMMON_NAME'), r.get('SCIENTIFIC_NAME')))

q = lambda s: "'" + s.replace("'", "''") + "'"
with open(out_path, 'w', encoding='utf-8') as f:
    f.write('-- BC fish species codes -> species ids (generated by scripts/build-species-aliases.py).\n')
    f.write('insert into public.species_aliases (alias_type, alias, species_id) values\n')
    f.write(',\n'.join(f"  ('bc-fish-code', {q(c)}, {q(s)})" for c, s in rows))
    f.write('\non conflict (alias_type, alias) do update set species_id = excluded.species_id;\n')
print(f'mapped {len(rows)} codes; unmatched {len(unmatched)} (generic/hybrid/non-fish codes, e.g. {unmatched[:8]})')
